"""Regenerate public/js/data-bundle.js after editing public/data files.
Only Python standard library is required. Run from the repo root:
    python tools/build_data_bundle.py
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "public" / "data"
OUTPUT = ROOT / "public" / "js" / "data-bundle.js"

bundle = {
    "khoroo": (DATA / "khoroo.csv").read_text(encoding="utf-8-sig"),
    "boundaries": json.loads((DATA / "boundaries.json").read_text(encoding="utf-8-sig")),
    "members_scope": (DATA / "members_scope.csv").read_text(encoding="utf-8-sig"),
    "members_monthly": (DATA / "members_monthly.csv").read_text(encoding="utf-8-sig"),
}
if not isinstance(bundle["boundaries"].get("rows"), list):
    raise ValueError("boundaries.json must contain a rows array")
for key in ("khoroo", "members_scope", "members_monthly"):
    if "\n" not in bundle[key]:
        raise ValueError(f"{key}.csv has no data rows")
OUTPUT.write_text(
    "/* Generated by tools/build_data_bundle.py from public/data; do not edit manually. */\n"
    + "window.UB_DATA_BUNDLE = "
    + json.dumps(bundle, ensure_ascii=False, separators=(",", ":"))
    + ";\n",
    encoding="utf-8",
)
print(f"Wrote {OUTPUT} ({OUTPUT.stat().st_size:,} bytes)")
